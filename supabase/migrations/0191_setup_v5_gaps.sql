 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
-- ★0191（便 OB-2 ⑤）: 初期設定の下書きを保存（owner・自 org の店・null＝削除＝完了時）。audit は書かない（入力途中の自動保存＝監査の対象外・完了は set_store_profile{setup_done} が残す）
declare
  v_org uuid := public.auth_org_id();
begin
  if v_org is null then raise exception 'forbidden'; end if;
  if public.auth_role() <> 'owner' then raise exception 'forbidden'; end if;
  if not exists (select 1 from public.stores s where s.id = p_store_id and s.org_id = v_org) then raise exception 'forbidden'; end if;
  if p_data is null then
    delete from public.setup_drafts where org_id = v_org and store_id = p_store_id;
    return;
  end if;
  if jsonb_typeof(p_data) <> 'object' or length(p_data::text) > 400000 then raise exception 'bad data'; end if;
  insert into public.setup_drafts (org_id, store_id, data, updated_by, updated_at)
  values (v_org, p_store_id, p_data, (select u.id from public.users u where u.auth_user_id = auth.uid() and u.is_active), now())
  on conflict (org_id, store_id) do update set data = excluded.data, updated_by = excluded.updated_by, updated_at = now();
end $function$;
revoke execute on function public.setup_draft_set(uuid, jsonb) from public, anon;
grant execute on function public.setup_draft_set(uuid, jsonb) to authenticated;

commit;

